            </div>
            <div class="info-card">
                <div class="research-icon" style="background: var(--color-blue);">🔬</div>
                <h3>Competitor Analysis</h3>
                <p>Audit of comparable platforms, gender-focused job boards, diversity-first recruiters, and mainstream job sites, to identify gaps, clichés to avoid, and opportunities to differentiate.</p>
            </div>
        </div>

        <div class="section-shell-pink">
            <p class="label-action">Key Insights</p>
            <h2>What the research revealed</h2>
            <p>Six clear themes emerged from research that directly shaped every brand, UX, and content decision that followed.</p>
            <ul class="findings-list">
                <li>Women identified "authenticity signals" immediately, they could spot performative inclusion within seconds of landing on a site</li>
                <li>Employers needed visible proof of platform credibility before committing, case studies and data mattered more than design alone</li>
                <li>The dual-audience structure required complete separation, mixing candidate and employer messaging created instant confusion and distrust</li>
                <li>Job listings needed strong employer context, company culture, diversity data, and flexible working policies were non-negotiable filters</li>
                <li>Competitors relied on tired visual clichés, purple gradients, stock photos of smiling women, creating a clear opportunity to differentiate</li>
                <li>Mobile was the primary browsing device for job seekers, a seamless mobile job search experience was essential, not optional</li>
            </ul>
        </div>

