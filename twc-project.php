        <div class="strategy-pillars two-column-grid">
            <div class="pillar">
                <h3>Authentic Brand Identity First</h3>
                <p>Build a visual identity that feels genuinely progressive, avoiding diversity design clichés and instead creating a bold, confident brand that signals quality and ambition without tokenism.</p>
            </div>
            <div class="pillar">
                <h3>Separate Journeys, One Platform</h3>
                <p>Design two distinct user journeys, one for candidates, one for employers, with tailored messaging, language, CTAs, and entry points. Each audience gets a path built entirely for them.</p>
            </div>
            <div class="pillar">
                <h3>Credibility Through Content &amp; Design</h3>
                <p>In the absence of existing testimonials and case data, let the design quality itself signal trust. Weave proof points, employer commitments, platform values, and early success stories, throughout every key page.</p>
            </div>
            <div class="pillar">
                <h3>Scalable, Team-Managed Platform</h3>
                <p>Build in WordPress with Elementor using a modular component library, so the Top Women Careers team can add job listings, update employer profiles, and publish content completely independently.</p>
